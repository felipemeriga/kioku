"""Portable SQL model; production schema is installed by Supabase migration."""

from sqlalchemy import (
    JSON,
    Boolean,
    Column,
    Float,
    ForeignKey,
    Integer,
    MetaData,
    String,
    Table,
    Text,
    UniqueConstraint,
)

metadata = MetaData()
jobs = Table(
    "tsukai_jobs",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("owner_id", String(128), nullable=False),
    Column("caller", String(20), nullable=False),
    Column("idempotency_key", String(200), nullable=False),
    Column("payload_hash", String(64), nullable=False),
    Column("request_sha256", String(64), nullable=False),
    Column("request", JSON, nullable=False),
    Column("status", String(30), nullable=False),
    Column("profile", String(30), nullable=False),
    Column("conversation_id", String(128)),
    Column("attempt_count", Integer, nullable=False, default=0),
    Column("next_seq", Integer, nullable=False, default=1),
    Column("created_at", Float, nullable=False),
    Column("updated_at", Float, nullable=False),
    Column("queue_deadline", Float, nullable=False),
    Column("result", JSON),
    Column("error", JSON),
    Column("cancel_requested", Boolean, nullable=False, default=False),
    UniqueConstraint("owner_id", "caller", "idempotency_key"),
)
attempts = Table(
    "tsukai_attempts",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("job_id", String(36), ForeignKey("tsukai_jobs.id"), nullable=False),
    Column("number", Integer, nullable=False),
    Column("fence", String(36), nullable=False),
    Column("worker_id", String(36), nullable=False),
    Column("status", String(30), nullable=False),
    Column("lease_until", Float, nullable=False),
    Column("deadline", Float, nullable=False),
    Column("started_at", Float, nullable=False),
    Column("finished_at", Float),
    Column("native_session_id", String(36), nullable=False),
    Column("resume", Boolean, nullable=False),
    Column("counter_segment", String(36), nullable=False),
    Column("usage", JSON),
    Column("error", JSON),
    UniqueConstraint("job_id", "number"),
)
events = Table(
    "tsukai_events",
    metadata,
    Column("job_id", String(36), ForeignKey("tsukai_jobs.id"), primary_key=True),
    Column("seq", Integer, primary_key=True),
    Column("attempt_id", String(36)),
    Column("type", String(50), nullable=False),
    Column("data", JSON, nullable=False),
    Column("created_at", Float, nullable=False),
)
sessions = Table(
    "tsukai_sessions",
    metadata,
    Column("owner_id", String(128), primary_key=True),
    Column("conversation_id", String(128), primary_key=True),
    Column("native_session_id", String(36), nullable=False, unique=True),
    Column("generation", Integer, nullable=False),
    Column("policy_fingerprint", String(64), nullable=False),
    Column("history", JSON, nullable=False),
    Column("state", String(30), nullable=False),
    Column("workspace", Text, nullable=False),
    Column("last_cost", Float),
    Column("last_counters", JSON),
    Column("updated_at", Float, nullable=False),
)
locks = Table(
    "tsukai_locks",
    metadata,
    Column("key", String(300), primary_key=True),
    Column("job_id", String(36), ForeignKey("tsukai_jobs.id"), nullable=False),
    Column("attempt_id", String(36)),
    Column("fence", String(36)),
    Column("lease_until", Float, nullable=False),
)
acks = Table(
    "tsukai_result_acks",
    metadata,
    Column("job_id", String(36), ForeignKey("tsukai_jobs.id"), primary_key=True),
    Column("consumer", String(100), primary_key=True),
    Column("reference", String(512), nullable=False),
    Column("created_at", Float, nullable=False),
)
